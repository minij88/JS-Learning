//Arithmetic Operators

//Addition
let num1=10;
let num2=20;
let sum=num1+num2;
console.log(sum);  //shows 30

let str1="Mini";
let str2="Jain";
console.log(str1+" "+str2);  //shows Mini Jain

//Subtraction
let num3=100;
let num4=45;
console.log(num3-num4);  //shows 55

//Multiplication
let num5=10;
let num6=75;
console.log(num5*num6);  //shows 750

//Division
let num7=1000;
let num8=100;
console.log(num7/num8);  //shows 10

//Modulus
let num9=130;
let num10=4;
console.log(num9%num10);  //shows 2

//Increment
let x=5;
x++;
let y=x;
console.log(y);  //shows 6

//Decrement
let value1=5;
value1--;
let value2=value1;
console.log(value2); //shows 4

//exponentiation
let base=8;
let result=base**2;
console.log(result); //shows 64


