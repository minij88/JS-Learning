//Assignment Operators

let x=10,y=5;
x=y;
console.log(x); //shows 5

x=10,y=5;
x+=y
console.log(x); //shows 15

x=10,y=5;
x-=y
console.log(x); //shows 5

x=10,y=5;
x*=y
console.log(x); //shows 50

x=10,y=5;
x/=y
console.log(x); //shows 2

x=10,y=5;
x%=y
console.log(x); //shows 0

x=10,y=5;
x**=y
console.log(x); //shows 100000