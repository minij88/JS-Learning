// for of loop is used to iterate over the values of an iterable.
// It works with Iterables (Arrays, Strings, Maps, Sets, etc.)
// It returns value

// for of loop with arrays
const arr=["a","b","c"];
for(let value of arr)
{
    console.log(value);
}  // shows a b c

// for of loop with String

